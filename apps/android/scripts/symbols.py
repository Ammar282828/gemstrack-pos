#!/usr/bin/env python3
"""Generates app/src/main/kotlin/erp/app/ui/icons/Symbols.kt from Google's Material Symbols Rounded SVGs.

Material Symbols is not a Compose library (material-icons-extended is the old Material Icons), so the app carries the few it draws as
path data: weight 400, grade 0, optical size 24, outline by default and the filled axis (fill 1) for a selected or active state.
The list of what to draw is scripts/symbols.txt (Kotlin name, Symbols name, flags); add a line there and run
    python3 scripts/symbols.py
(network; the SVGs come from a pinned commit of github.com/google/material-design-icons and are cached in $TMPDIR).
"""
import os, re, sys, tempfile, urllib.request, concurrent.futures as cf

REF = "10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7"
BASE = f"https://raw.githubusercontent.com/google/material-design-icons/{REF}/symbols/web"
here = os.path.dirname(os.path.abspath(__file__))
out_path = os.path.join(here, "..", "app", "src", "main", "kotlin", "erp", "app", "ui", "icons", "Symbols.kt")
cache = os.path.join(os.environ.get("TMPDIR", tempfile.gettempdir()), "material-symbols-" + REF[:8])
os.makedirs(cache, exist_ok=True)


def svg(name, filled):
    suffix = "_fill1_24px.svg" if filled else "_24px.svg"
    local = os.path.join(cache, name + suffix)
    if not os.path.exists(local):
        url = f"{BASE}/{name}/materialsymbolsrounded/{name}{suffix}"
        with urllib.request.urlopen(url, timeout=60) as r:
            open(local, "wb").write(r.read())
    return open(local, encoding="utf-8").read()


def path_data(text):
    ds = re.findall(r'<path[^>]* d="([^"]+)"', text)
    if not ds:
        raise SystemExit("no path in an SVG")
    return " ".join(ds)


rows = []
for line in open(os.path.join(here, "symbols.txt"), encoding="utf-8"):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    parts = line.split()
    flags = parts[2] if len(parts) > 2 else ""
    rows.append((parts[0], parts[1], "F" in flags, "M" in flags, "+" in flags))

jobs = set()
for kt, sym, f, m, plus in rows:
    jobs.add((sym, f))
    if plus:
        jobs.add((sym, True))
jobs = sorted(jobs)
with cf.ThreadPoolExecutor(8) as ex:
    data = dict(zip(jobs, ex.map(lambda j: path_data(svg(*j)), jobs)))


def prop(kt, sym, filled, mirror, indent):
    return f'{indent}val {kt}: ImageVector by lazy {{ symbol("{sym}", {"true" if mirror else "false"}, "{data[(sym, filled)]}") }}\n'


with open(out_path, "w", encoding="utf-8") as o:
    o.write("// GENERATED by scripts/symbols.py from scripts/symbols.txt (Material Symbols Rounded, weight 400, grade 0, optical size 24). Do not edit.\n")
    o.write("package erp.app.ui.icons\n\nimport androidx.compose.ui.graphics.vector.ImageVector\n\n")
    o.write("/** The icons the app draws: outline by default; `Symbols.Fill` is the filled axis for a selected or active state. */\n")
    o.write("object Symbols {\n")
    for kt, sym, f, m, plus in rows:
        o.write(prop(kt, sym, f, m, "    "))
    o.write("\n    /** The same places filled: the chosen tab, a toggled button. */\n    object Fill {\n")
    for kt, sym, f, m, plus in rows:
        if plus:
            o.write(prop(kt, sym, True, m, "        "))
    o.write("    }\n}\n")
print(len(rows), "icons,", sum(1 for r in rows if r[4]), "filled twins ->", os.path.relpath(out_path))
