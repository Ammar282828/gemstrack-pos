#!/usr/bin/env bash
# Renders each house's launcher icons and logos from the iPhone's asset catalog (needs ImageMagick 6+ and python3).
# Outputs go to app/src/<house>/res and are committed; run this when the iPhone's art changes.
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
cat="$here/../iphone/App/Resources/Assets.xcassets"
IM=convert
command -v "$IM" >/dev/null || { echo "ImageMagick (convert) is required" >&2; exit 1; }

# the imageset's file for a scale and appearance, straight from its Contents.json
pick() { # dir scale dark(0|1)
  python3 -I - "$1/Contents.json" "$2" "$3" <<'PY'
import json, sys
path, scale, dark = sys.argv[1], sys.argv[2], sys.argv[3] == "1"
for im in json.load(open(path))["images"]:
    is_dark = any(a.get("value") == "dark" for a in im.get("appearances", []))
    if im.get("scale", scale) == scale and is_dark == dark and "filename" in im:
        print(im["filename"]); break
PY
}

for house in taheri mina; do
  out="$here/app/src/$house/res"
  rm -rf "$out"
  art="$cat/AppIcon-$house.appiconset/icon-1024.png"
  w="$(mktemp -d)"

  # The art is a wordmark on one flat colour: that colour is the adaptive background.
  bg="#$($IM "$art" -format '%[hex:p{2,2}]' info:)"
  mkdir -p "$out/values"
  cat > "$out/values/ic_launcher_background.xml" <<X
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/icons.sh from the iPhone's app icon. -->
<resources>
    <color name="ic_launcher_background">$bg</color>
</resources>
X

  # Wordmark box, then a square around it; the first argument is the mark's percent of the square's width.
  box="$($IM "$art" -fuzz 3% -format '%@' info:)" # WxH+X+Y
  bw=${box%%x*}; rest=${box#*x}; bh=${rest%%+*}; rest=${rest#*+}; bx=${rest%%+*}; by=${rest#*+}
  cx=$(( 1024 + bx + bw / 2 )); cy=$(( 1024 + by + bh / 2 ))
  $IM "$art" -background "$bg" -gravity center -extent 3072x3072 +repage "$w/big.png"
  frame() { # percent out.png size
    local s=$(( bw * 100 / $1 ))
    $IM "$w/big.png" -crop "${s}x${s}+$(( cx - s / 2 ))+$(( cy - s / 2 ))" +repage -resize "$3x$3" "$2"
  }
  # monochrome: the mark's difference from the background becomes alpha, drawn in black
  mono() { # percent out.png size
    local s=$(( bw * 100 / $1 ))
    $IM "$w/big.png" -crop "${s}x${s}+$(( cx - s / 2 ))+$(( cy - s / 2 ))" +repage -resize "$3x$3" \
      \( +clone -fill "$bg" -colorize 100 \) -compose difference -composite -colorspace Gray -auto-level \
      -alpha copy -channel RGB -evaluate set 0 +channel "$2"
  }

  for d in "mdpi 1" "hdpi 1.5" "xhdpi 2" "xxhdpi 3" "xxxhdpi 4"; do
    set -- $d; dir="$out/mipmap-$1"; mkdir -p "$dir"
    adaptive=$(python3 -c "print(round(108*$2))"); legacy=$(python3 -c "print(round(48*$2))")
    frame 60 "$dir/ic_launcher_foreground.png" "$adaptive"   # mark inside the 66% safe zone
    mono 60 "$dir/ic_launcher_monochrome.png" "$adaptive"
    frame 72 "$w/l.png" "$legacy"
    # legacy: rounded square, and a circle
    r=$(( legacy * 18 / 100 ))
    $IM "$w/l.png" \( +clone -alpha extract -fill black -colorize 100 -fill white \
       -draw "roundrectangle 0,0 $((legacy-1)),$((legacy-1)) $r,$r" \) -alpha off -compose CopyOpacity -composite "$dir/ic_launcher.png"
    $IM "$w/l.png" \( +clone -alpha extract -fill black -colorize 100 -fill white \
       -draw "circle $((legacy/2)),$((legacy/2)) $((legacy/2)),0" \) -alpha off -compose CopyOpacity -composite "$dir/ic_launcher_round.png"
  done

  mkdir -p "$out/mipmap-anydpi-v26"
  for n in ic_launcher ic_launcher_round; do
    cat > "$out/mipmap-anydpi-v26/$n.xml" <<'X'
<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
X
  done

  # In-app logo (light/dark) and the splash mark; nodpi so the pixels are used as they are.
  mkdir -p "$out/drawable-nodpi" "$out/drawable-night-nodpi"
  brand="$cat/BrandLogo-$house.imageset"
  lf="$(python3 -I - "$brand/Contents.json" <<'PY'
import json, sys
im = json.load(open(sys.argv[1]))["images"]
d = {("dark" if any(a.get("value") == "dark" for a in i.get("appearances", [])) else "light"): i["filename"] for i in im}
print(d["light"], d["dark"])
PY
)"
  set -- $lf
  cp "$brand/$1" "$out/drawable-nodpi/brand_logo.png"
  cp "$brand/$2" "$out/drawable-night-nodpi/brand_logo.png"

  launch="$cat/LaunchLogo-$house.imageset"
  if [ -d "$launch" ]; then
    l="$(pick "$launch" 3x 0)"; d="$(pick "$launch" 3x 1)"
    cp "$launch/$l" "$out/drawable-nodpi/launch_logo.png"
    cp "$launch/$d" "$out/drawable-night-nodpi/launch_logo.png"
    # the splash screen wants a square icon: the wide mark centred on a transparent square
    for v in "drawable-nodpi" "drawable-night-nodpi"; do
      sz=$($IM "$out/$v/launch_logo.png" -format '%w' info:)
      $IM "$out/$v/launch_logo.png" -background none -gravity center -extent "${sz}x${sz}" "$out/$v/splash_icon.png"
    done
  fi
  rm -rf "$w"
  echo "$house: icons and logos in app/src/$house/res"
done
