/**
 * The machines as data (for the iPhone and Android apps, which mirror the labels, tones and moves instead of re-deciding
 * them) and as Markdown (docs/state-machines.md, for people and for agents working on the code or through the AI keys).
 * `npm run machines:export` writes both; machines.test.ts fails when either is stale, as nav-export does for the menu.
 */
import { MACHINES } from './index';
import type { Machine } from './machine';
import { SETTLEMENT_DERIVED } from './settlement';

type AnyMachine = Machine<string, never>;

export interface MachineJson {
  name: string; field: string; states: string[]; final: string[];
  labels: Record<string, string>; tones: Record<string, string>;
  moves: { from: string[] | '*'; to: string; event: string; when?: string; note?: string }[];
}

/** A status the shop never stores but derives from other fields (labels and tones for the apps, the rule in words). */
export interface DerivedJson { name: string; field: string; states: string[]; labels: Record<string, string>; tones: Record<string, string>; rule: string }

const DERIVED: readonly DerivedJson[] = [SETTLEMENT_DERIVED].map(d => ({
  name: d.name, field: d.field, states: [...d.states], labels: { ...d.labels }, tones: { ...d.tones }, rule: d.rule,
}));

export function machinesJson(): { version: 1; machines: MachineJson[]; derived: DerivedJson[] } {
  return {
    version: 1,
    derived: DERIVED.map(d => ({ ...d, states: [...d.states], labels: { ...d.labels }, tones: { ...d.tones } })),
    machines: (MACHINES as unknown as AnyMachine[]).map(m => ({
      name: m.name, field: m.field, states: [...m.states], final: [...m.final], labels: { ...m.labels }, tones: { ...m.tones },
      moves: m.moves.map(mv => ({
        from: mv.from === '*' ? '*' : [...mv.from], to: mv.to, event: mv.event,
        ...(mv.guardNote ? { when: mv.guardNote } : {}), ...(mv.note ? { note: mv.note } : {}),
      })),
    })),
  };
}

export const machinesJsonText = () => `${JSON.stringify(machinesJson(), null, 2)}\n`;

export function machinesMarkdown(): string {
  const out: string[] = [
    '# State machines',
    '',
    '<!-- Generated by `npm run machines:export` from src/lib/machines/index.ts. Do not edit by hand. -->',
    '',
    'Every status in the ERP that changes over time, with every move it allows. The server refuses any other move inside the',
    'same transaction as the write and answers **409** with `{ error, machine, from, to, allowed: [{ to, event }] }`, so a',
    'screen, an app or an agent always learns what it can do instead. `set` is a person choosing the status; the other events',
    'are named actions (Finalize, Refund, Book with TCS) or the server\'s own runs (Shopify, the website, the five-minute tick).',
    '',
  ];
  for (const m of MACHINES as unknown as AnyMachine[]) {
    out.push(`## ${m.name}`, '', `\`${m.field}\` · states: ${m.states.map(s => `\`${s}\` (${m.labels[s]})`).join(', ')}${m.final.length ? ` · final: ${m.final.map(s => `\`${s}\``).join(', ')}` : ''}`, '');
    out.push('| From | To | Event | Only when | Note |', '|---|---|---|---|---|');
    for (const mv of m.moves) {
      out.push(`| ${mv.from === '*' ? 'any' : mv.from.map(s => `\`${s}\``).join(', ')} | \`${mv.to}\` | ${mv.event} | ${mv.guardNote ?? ''} | ${mv.note ?? ''} |`);
    }
    out.push('');
  }
  out.push('## Derived states', '', 'Not stored: worked out from other fields by one function each (`src/lib/machines/settlement.ts`), so every screen, PDF and message agrees.', '');
  for (const d of DERIVED) {
    out.push(`### ${d.name}`, '', `\`${d.field}\` · states: ${d.states.map(s => `\`${s}\` (${d.labels[s]}, ${d.tones[s]})`).join(', ')}`, '', d.rule, '');
  }
  return out.join('\n');
}
