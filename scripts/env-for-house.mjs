// Write .env.<house>.local from apphosting.yaml + apphosting.<house>.yaml, so a
// local `next dev` runs as that house with exactly the values its backend has.
//
//   node scripts/env-for-house.mjs taheri   →  .env.taheri.local
//   node scripts/env-for-house.mjs mina     →  .env.mina.local
//
// Plain values are copied. A `secret:` has no value in the repo, so it is
// written as an empty line for you to fill from Secret Manager (or leave empty:
// every feature that wants one says so and works without it). Existing
// non-empty secret lines in the file are kept, so re-running never blanks a
// key you already pasted.

import fs from 'node:fs';
import yaml from 'yaml';

const house = process.argv[2];
if (!['taheri', 'mina'].includes(house)) { console.error('usage: node scripts/env-for-house.mjs <taheri|mina>'); process.exit(1); }
const out = `.env.${house}.local`;
const load = (f) => (yaml.parse(fs.readFileSync(f, 'utf8')).env || []);
const merged = new Map();
for (const e of [...load('apphosting.yaml'), ...load(`apphosting.${house}.yaml`)]) merged.set(e.variable, e);
const existing = new Map(fs.existsSync(out) ? fs.readFileSync(out, 'utf8').split('\n').filter(l => /^[A-Z_0-9]+=/.test(l)).map(l => l.split(/=(.*)/s).slice(0, 2)) : []);
const lines = [`# ${house}: generated by scripts/env-for-house.mjs from apphosting.yaml + apphosting.${house}.yaml — edit those, not this.`];
for (const [k, e] of merged) {
  if (e.secret !== undefined) lines.push(`# secret ${e.secret} — paste from Secret Manager, or leave empty`, `${k}=${existing.get(k) || ''}`);
  else lines.push(`${k}=${String(e.value)}`);
}
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${out}: ${merged.size} variables (${[...merged.values()].filter(e => e.secret !== undefined).length} secrets to fill)`);
